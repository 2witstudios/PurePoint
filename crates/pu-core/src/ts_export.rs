/// The JSON as the daemon emits it, so the samples show every field it writes.
fn reserialize<T: serde::Serialize + serde::de::DeserializeOwned>(json: &str) -> String {
    let value: T = serde_json::from_str(json).unwrap_or_else(|e| panic!("{e}: {json}"));
    serde_json::to_string(&value).unwrap()
}

fn samples_ts() -> String {
    let mut out = String::from(NOTE);
    out.push_str(
        "// Real JSON the daemon accepts and sends: `tsc` checks it against the generated types.\n",
    );
    out.push_str("import type { Request } from \"./Request\";\nimport type { Response } from \"./Response\";\n\n");
    let sections = [
        (
            "requestInputs",
            "Request",
            REQUEST_INPUTS
                .iter()
                .map(|s| s.to_string())
                .collect::<Vec<_>>(),
        ),
        (
            "requestOutputs",
            "Request",
            REQUEST_INPUTS
                .iter()
                .map(|s| reserialize::<Request>(s))
                .collect(),
        ),
        (
            "responseOutputs",
            "Response",
            response_inputs()
                .iter()
                .map(|s| reserialize::<Response>(s))
                .collect(),
        ),
    ];
    for (name, ty, items) in sections {
        // Requests written by hand must parse too.
        for item in &items {
            if ty == "Request" {
                reserialize::<Request>(item);
            }
        }
        writeln!(out, "export const {name}: {ty}[] = [").unwrap();
        for item in items {
            writeln!(out, "  {item},").unwrap();
        }
        out.push_str("];\n\n");
    }
    out.truncate(out.trim_end().len());
    out.push('\n');
    out
}

fn ts_files(dir: &Path, base: &Path, out: &mut Vec<String>) {
    for entry in fs::read_dir(dir).unwrap() {
        let path = entry.unwrap().path();
        if path.is_dir() {
            ts_files(&path, base, out);
        } else if path.extension().is_some_and(|e| e == "ts") {
            let rel = path.strip_prefix(base).unwrap().with_extension("");
            out.push(rel.to_string_lossy().replace('\\', "/"));
        }
    }
}

/// Writes the bindings into `dir`, which must be empty or missing. Returns the
/// number of exported types.
fn export(dir: &Path) -> usize {
    let cfg = Config::new()
        .with_out_dir(dir)
        // JSON.parse yields `number`; the protocol's u64/i64 values stay below 2^53.
        .with_large_int("number");
    Request::export_all(&cfg).unwrap();
    Response::export_all(&cfg).unwrap();
    Manifest::export_all(&cfg).unwrap();
    ProjectConfig::export_all(&cfg).unwrap();
    LaunchArgs::export_all(&cfg).unwrap();

    let mut types = Vec::new();
    ts_files(dir, dir, &mut types);
    types.sort();

    fs::write(
        dir.join("protocolVersion.ts"),
        format!(
            "{NOTE}\n/** Wire protocol version (`pu_core::protocol::PROTOCOL_VERSION`). */\nexport const PROTOCOL_VERSION = {PROTOCOL_VERSION};\n"
        ),
    )
    .unwrap();
    let mut index = format!("{NOTE}\nexport {{ PROTOCOL_VERSION }} from \"./protocolVersion\";\n");
    for ty in &types {
        writeln!(index, "export type * from \"./{ty}\";").unwrap();
    }
    fs::write(dir.join("index.ts"), index).unwrap();
    fs::write(dir.join("samples.ts"), samples_ts()).unwrap();
    types.len()
}

#[test]
fn export_typescript_bindings() {
    match std::env::var_os("PU_TS_EXPORT_DIR") {
        Some(dir) => {
            let dir = PathBuf::from(dir);
            // Guard the wipe below against a mistyped variable.
            assert_eq!(
                dir.file_name().and_then(|n| n.to_str()),
                Some("generated"),
                "PU_TS_EXPORT_DIR must name a directory called `generated`"
            );
            if dir.exists() {
                fs::remove_dir_all(&dir).unwrap();
            }
            fs::create_dir_all(&dir).unwrap();
            let count = export(&dir);
            println!("exported {count} types to {}", dir.display());
        }
        None => {
            let dir = tempfile::tempdir().unwrap();
            assert!(export(dir.path()) > 50);
        }
    }
}
