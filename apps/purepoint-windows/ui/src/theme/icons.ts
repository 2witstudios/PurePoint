export type SfSymbolName = keyof typeof SF_SYMBOLS;

/**
 * Lucide icons whose glyph has an inner mark (a check, a cross, people) that a solid fill would hide.
 * Their `.fill` symbols get a translucent tint; every other `.fill` symbol is filled solid.
 */
const TINTED_WHEN_FILLED: ReadonlySet<string> = new Set([
  'circle-check',
  'circle-x',
  'circle-minus',
  'triangle-exclamation-point',
  'users-round',
]);

/** How the Mac draws a symbol: outlined, or filled (`.fill` variants) solid or as a tint. */
export function symbolFill(name: SfSymbolName): 'none' | 'solid' | 'tint' {
  if (!name.endsWith('.fill')) return 'none';
  return TINTED_WHEN_FILLED.has(SF_SYMBOLS[name][0]) ? 'tint' : 'solid';
}

/** The Lucide component for an SF Symbol. */
export const lucideIconFor = (name: SfSymbolName): LucideIcon => SF_SYMBOLS[name][1];
